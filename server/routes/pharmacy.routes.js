const router = require("express").Router();
const role = require("../middlewares/roles");
const controller = require("../controllers/pharmacy.controller");
const payment = require("../services/pharmacy-payments");
const { authorized, serialize } = require("../services/pharmacy");
router.use(require("../middlewares/auth"));
router.use((_req, res, next) => { res.set("Cache-Control", "no-store, private"); next(); });
router.get("/team", role(["staff"]), controller.team);
router.post("/team", role(["staff"]), controller.link);
router.post("/send/:recordId", role(["doctor"]), controller.send);
router.get("/orders", role(["patient", "pharmacist"]), controller.list);
router.get("/orders/:id", role(["patient", "pharmacist"]), controller.get);
router.patch("/orders/:id/prepare", role(["pharmacist"]), controller.prepare);
router.post("/orders/:id/ready", role(["pharmacist"]), controller.ready);
router.post("/orders/:id/paid", role(["pharmacist"]), controller.paid);
router.post("/orders/:id/counter", role(["patient"]), async (req, res) => res.json(serialize(await payment.counter(await authorized(req.user, req.params.id)))));
router.post("/orders/:id/checkout", role(["patient"]), require("../middlewares/rateLimit")({ limit: 20 }), async (req, res) => res.json(await payment.checkout(await authorized(req.user, req.params.id))));
router.post("/orders/:id/reconcile", role(["patient"]), require("../middlewares/rateLimit")({ limit: 30 }), async (req, res) => res.json(serialize(await payment.reconcile(await authorized(req.user, req.params.id)))));
module.exports = router;
